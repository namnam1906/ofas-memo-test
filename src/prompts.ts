export type Purpose = "ทราบ" | "อนุมัติ" | "ดำเนินการ" | "อนุเคราะห์" | string;

export function closingPhrase(purpose: Purpose): string {
  switch (purpose) {
    case "ทราบ":
      return "จึงเรียนมาเพื่อโปรดทราบ";
    case "อนุมัติ":
      return "จึงเรียนมาเพื่อโปรดพิจารณาอนุมัติ";
    case "ดำเนินการ":
      return "จึงเรียนมาเพื่อโปรดพิจารณาดำเนินการต่อไป";
    case "อนุเคราะห์":
      return "จึงเรียนมาเพื่อโปรดพิจารณาให้ความอนุเคราะห์ด้วย";
    default:
      return "จึงเรียนมาเพื่อโปรดพิจารณา";
  }
}

