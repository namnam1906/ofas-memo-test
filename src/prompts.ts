export function buildDraftUserPrompt(input: DraftInput): string {
  return [
    input.orgName ? `ส่วนงาน: ${input.orgName}` : "",
    input.subject ? `เรื่อง: ${input.subject}` : "",
    input.addressee ? `เรียน: ${input.addressee}` : "",
    "ประเด็น/ข้อมูลที่ต้องการสื่อสาร (ภาษาพูดหรือหัวข้อดิบจากผู้ใช้):",
    input.notes,
  ]
    .filter(Boolean)
    .join("\n");
}

